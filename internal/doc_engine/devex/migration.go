// APIDelta tracks breaking or notable changes in public interfaces between two revisions.
type APIDelta struct {
	DeletedFunctions []string `json:"deleted_functions"`
	ModifiedSignatures []struct {
		Name   string `json:"name"`
		Before string `json:"before"`
		After  string `json:"after"`
	} `json:"modified_signatures"`
	RenamedFields []struct {
		OldName string `json:"old_name"`
		NewName string `json:"new_name"`
		Struct  string `json:"struct"`
	} `json:"renamed_fields"`
	// RenamedConfigVars pairs env vars that disappeared with similar new ones.
	RenamedConfigVars []struct {
		OldName string `json:"old_name"`
		NewName string `json:"new_name"`
	} `json:"renamed_config_vars"`
	// RemovedConfigVars lists env vars deleted with no similar replacement.
	RemovedConfigVars []string `json:"removed_config_vars"`
}

// GenerateMigrationGuide analyzes symbol and commit differences between two git refs
// and produces a comprehensive migration guide markdown document.
func GenerateMigrationGuide(repoRoot, ref1, ref2, outFile string) (string, error) {
	delta, commits, err := computeRevisionDiff(repoRoot, ref1, ref2)
	diffFailed := err != nil
	var diffErr error
	if diffFailed {
		diffErr = err
		commits = []string{fmt.Sprintf("Update between %s and %s", ref1, ref2)}
	}

	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("# Migration Guide: %s → %s\n\n", ref1, ref2))
	sb.WriteString("> Auto-generated by GlassMarble Documentation Intelligence Engine (Pillar 24).\n")
	sb.WriteString(fmt.Sprintf("> Computed from AST symbol diffing and commit reasoning between `%s` and `%s`.\n\n", ref1, ref2))

	sb.WriteString("## Executive Summary\n\n")
	sb.WriteString(fmt.Sprintf("- **Source Reference:** `%s`\n", ref1))
	sb.WriteString(fmt.Sprintf("- **Target Reference:** `%s`\n", ref2))
	sb.WriteString(fmt.Sprintf("- **Generated On:** %s\n", time.Now().Format("2006-01-02 15:04:05 MST")))
	sb.WriteString(fmt.Sprintf("- **Breaking Changes Detected:** %d\n\n", len(delta.DeletedFunctions)+len(delta.ModifiedSignatures)+len(delta.RenamedFields)))

	// Section 1: Breaking Changes
	sb.WriteString("## Breaking Changes & Interface Deltas\n\n")

	if len(delta.DeletedFunctions) > 0 {
		sb.WriteString("### ⚠️ Deleted Public Functions & Methods\n\n")
		sb.WriteString("The following exported symbols were removed and are no longer available:\n\n")
		for _, fn := range delta.DeletedFunctions {
			sb.WriteString(fmt.Sprintf("- ❌ `func %s`\n", displayNameOf(fn)))
		}
		sb.WriteString("\n")
	}

	if len(delta.ModifiedSignatures) > 0 {
		sb.WriteString("### 🔄 Modified Function Signatures\n\n")
		sb.WriteString("| Function | Previous Signature | New Signature |\n")
		sb.WriteString("| :--- | :--- | :--- |\n")
		for _, sig := range delta.ModifiedSignatures {
			sb.WriteString(fmt.Sprintf("| **`%s`** | `%s` | `%s` |\n", displayNameOf(sig.Name), sig.Before, sig.After))
		}
		sb.WriteString("\n")
	}

	if len(delta.RenamedFields) > 0 {
		sb.WriteString("### 🏷️ Renamed Struct Fields & Parameters\n\n")
		sb.WriteString("| Struct | Old Field | New Field |\n")
		sb.WriteString("| :--- | :--- | :--- |\n")
		for _, f := range delta.RenamedFields {
			sb.WriteString(fmt.Sprintf("| `%s` | `~~%s~~` | `**%s**` |\n", f.Struct, f.OldName, f.NewName))
		}
		sb.WriteString("\n")
	}

	if diffFailed {
		// computeRevisionDiff failed (bad ref, unfetched tag, git error): delta
		// is the zero value, not a verified "nothing changed" result. Say so
		// explicitly rather than shipping a confident-looking "no breaking
		// changes" claim the tool never actually verified.
		sb.WriteString(fmt.Sprintf("⚠️ Automated interface diffing between `%s` and `%s` could not run (%v). "+
			"Breaking-change detection below is incomplete — review the interface manually.\n\n", ref1, ref2, diffErr))
	} else if len(delta.DeletedFunctions) == 0 && len(delta.ModifiedSignatures) == 0 && len(delta.RenamedFields) == 0 {
		sb.WriteString("✅ No breaking interface changes or deleted symbols detected in public surfaces.\n\n")
	}

	// Section 1b: Configuration variable renames (Pillar 24).
	if len(delta.RenamedConfigVars) > 0 {
		sb.WriteString("### 🔧 Renamed Configuration Variables\n\n")
		sb.WriteString("| Old Variable | New Variable |\n")
		sb.WriteString("| :--- | :--- |\n")
		for _, r := range delta.RenamedConfigVars {
			sb.WriteString(fmt.Sprintf("| `~~%s~~` | `**%s**` |\n", r.OldName, r.NewName))
		}
		sb.WriteString("\n")
	}
	if len(delta.RemovedConfigVars) > 0 {
		sb.WriteString("### 🗑️ Removed Configuration Variables\n\n")
		sb.WriteString("The following environment variables were removed with no replacement:\n\n")
		for _, v := range delta.RemovedConfigVars {
			sb.WriteString(fmt.Sprintf("- ❌ `%s`\n", v))
		}
		sb.WriteString("\n")
	}

	// Section 1c: Migration code examples — Before/After call sites per modified signature.
	if len(delta.ModifiedSignatures) > 0 {
		sb.WriteString("## Migration Code Examples\n\n")
		for _, sig := range delta.ModifiedSignatures {
			short := displayNameOf(sig.Name)
			sb.WriteString(fmt.Sprintf("### `%s`\n\n", short))
			sb.WriteString("Update call sites from:\n\n")
			sb.WriteString("```go\n")
			sb.WriteString(fmt.Sprintf("// before: %s\nout := %s(/* update args */)\n", sig.Before, short))
			sb.WriteString("```\n\n")
			sb.WriteString("to:\n\n")
			sb.WriteString("```go\n")
			sb.WriteString(fmt.Sprintf("// after: %s\nout := %s(/* update args */)\n", sig.After, short))
			sb.WriteString("```\n\n")
			sb.WriteString(fmt.Sprintf("> Rewrite note: update arguments at call sites of `%s` to match the new signature `%s`.\n\n", short, sig.After))
		}
	}

	// Section 2: Commit History
	sb.WriteString("## Commit History & Architectural Intent\n\n")
	for _, c := range commits {
		if strings.TrimSpace(c) != "" {
			sb.WriteString(fmt.Sprintf("- %s\n", c))
		}
	}
	sb.WriteString("\n")

	// Section 3: Recommended Upgrade Steps
	sb.WriteString("## Recommended Upgrade Steps\n\n")
	sb.WriteString(fmt.Sprintf("1. Update repository dependency or check out `%s`.\n", ref2))
	sb.WriteString("2. Compile and run test suite: `go test ./...`.\n")
	sb.WriteString("3. Synchronize living documentation: `gmb doc`.\n")
	sb.WriteString("4. Verify zero documentation drift: `gmb doc check`.\n")

	result := sb.String()
	if outFile != "" {
		if _, err := storage.AtomicWriteFile(outFile, []byte(result)); err != nil {
			return "", err
		}
	}

	return result, nil
}

func computeRevisionDiff(repoRoot, ref1, ref2 string) (APIDelta, []string, error) {
	delta := APIDelta{}
	cmd := exec.Command("git", "log", fmt.Sprintf("%s..%s", ref1, ref2), "--oneline")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return delta, nil, err
	}

	lines := strings.Split(strings.TrimSpace(string(out)), "\n")

	// AKG symbol diffing per Pillar 24: extract exported symbols at each ref
	// via `git show <ref>:<go-file>` so renames/deletions/signature changes
	// are detected deterministically without checking out the old tree.
	before := extractExportedSymbolsAtRef(repoRoot, ref1)
	after := extractExportedSymbolsAtRef(repoRoot, ref2)

	for fn, beforeSig := range before {
		afterSig, ok := after[fn]
		if !ok {
			delta.DeletedFunctions = append(delta.DeletedFunctions, fn)
			continue
		}
		if normalizeSig(beforeSig) != normalizeSig(afterSig) {
			delta.ModifiedSignatures = append(delta.ModifiedSignatures, struct {
				Name   string `json:"name"`
				Before string `json:"before"`
				After  string `json:"after"`
			}{Name: fn, Before: beforeSig, After: afterSig})
		}
	}

	// Struct field renames: heuristic — a field deleted from a struct at
	// ref1 that has a same-typed new field at ref2 is reported as renamed.
	beforeFields := extractStructFieldsAtRef(repoRoot, ref1)
	afterFields := extractStructFieldsAtRef(repoRoot, ref2)
	for st, bf := range beforeFields {
		af, ok := afterFields[st]
		if !ok {
			continue
		}
		for oldName, oldType := range bf {
			if _, stillThere := af[oldName]; stillThere {
				continue
			}
			for newName, newType := range af {
				if _, wasThere := bf[newName]; wasThere {
					continue
				}
				if newType == oldType {
					delta.RenamedFields = append(delta.RenamedFields, struct {
						OldName string `json:"old_name"`
						NewName string `json:"new_name"`
						Struct  string `json:"struct"`
					}{OldName: oldName, NewName: newName, Struct: st})
					break
				}
			}
		}
	}

	// Fallback: if neither ref resolves (shallow clone, missing ref), fall
	// back to parsing the unified diff for deleted exported funcs so the
	// guide still reports breaking changes instead of "no changes".
	if len(before) == 0 && len(after) == 0 {
		delta = diffFallbackDelta(repoRoot, ref1, ref2)
	}

	// Config-var renames: diff env-var sets observed in the unified diff
	// between the two refs (Pillar 24). Runs regardless of the symbol-diff
	// path above since it only needs `git diff` output.
	renamed, removedVars := diffConfigVarRenames(repoRoot, ref1, ref2)
	delta.RenamedConfigVars = renamed
	delta.RemovedConfigVars = removedVars

	return delta, lines, nil
}

