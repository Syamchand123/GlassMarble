// listGoFilesAtRef returns repo-relative .go paths visible at the given ref.
func listGoFilesAtRef(repoRoot, ref string) []string {
	cmd := exec.Command("git", "ls-tree", "-r", "--name-only", ref)
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return nil
	}
	var files []string
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasSuffix(line, ".go") && !strings.HasSuffix(line, "_test.go") {
			files = append(files, line)
		}
	}
	return files
}

// showFileAtRef returns the content of path as it existed at ref.
func showFileAtRef(repoRoot, ref, path string) (string, bool) {
	cmd := exec.Command("git", "show", ref+":"+path)
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return "", false
	}
	return string(out), true
}

// extractExportedSymbolsAtRef maps exported func/method name → signature line.
// Keys are file-qualified (path::Recv.Name) so same-named symbols in
// different packages never collide; display names strip the file prefix.
func extractExportedSymbolsAtRef(repoRoot, ref string) map[string]string {
	result := make(map[string]string)
	for _, f := range listGoFilesAtRef(repoRoot, ref) {
		content, ok := showFileAtRef(repoRoot, ref, f)
		if !ok {
			continue
		}
		for _, line := range strings.Split(content, "\n") {
			trimmed := strings.TrimSpace(line)
			if !strings.HasPrefix(trimmed, "func ") {
				continue
			}
			name := exportedFuncName(trimmed)
			if name == "" {
				continue
			}
			key := f + "::" + name
			if _, exists := result[key]; !exists {
				result[key] = trimmed
			}
		}
	}
	return result
}

// extractStructFieldsAtRef maps struct name → field name → field type.
// Keys are file-qualified (path::Struct) for the same reason as above.
func extractStructFieldsAtRef(repoRoot, ref string) map[string]map[string]string {
	result := make(map[string]map[string]string)
	for _, f := range listGoFilesAtRef(repoRoot, ref) {
		content, ok := showFileAtRef(repoRoot, ref, f)
		if !ok {
			continue
		}
		lines := strings.Split(content, "\n")
		var curStruct string
		inStruct := false
		braceDepth := 0
		for _, line := range lines {
			trimmed := strings.TrimSpace(line)
			if !inStruct {
				if st, ok := parseTypeStructLine(trimmed); ok && isExportedGoIdent(st) {
					curStruct = st
					inStruct = true
					braceDepth = strings.Count(line, "{") - strings.Count(line, "}")
					if _, exists := result[curStruct]; !exists {
						result[curStruct] = make(map[string]string)
					}
					continue
				}
				continue
			}
			braceDepth += strings.Count(line, "{") - strings.Count(line, "}")
			if braceDepth <= 0 {
				inStruct = false
				curStruct = ""
				continue
			}
			if trimmed == "" || strings.HasPrefix(trimmed, "//") {
				continue
			}
			fields := strings.Fields(trimmed)
			if len(fields) >= 2 && isExportedGoIdent(fields[0]) {
				result[curStruct][fields[0]] = fields[1]
			}
		}
	}
	return result
}

// diffFallbackDelta parses the unified diff when ref content is unavailable.
func diffFallbackDelta(repoRoot, ref1, ref2 string) APIDelta {
	delta := APIDelta{}
	cmd := exec.Command("git", "diff", ref1, ref2, "--", "*.go")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return delta
	}
	removed := make(map[string]string)
	added := make(map[string]string)
	for _, line := range strings.Split(string(out), "\n") {
		if len(line) < 2 {
			continue
		}
		marker, body := line[0], strings.TrimSpace(line[1:])
		if !strings.HasPrefix(body, "func ") {
			continue
		}
		name := exportedFuncName(body)
		if name == "" {
			continue
		}
		switch marker {
		case '-':
			removed[name] = body
		case '+':
			added[name] = body
		}
	}
	for name, before := range removed {
		after, ok := added[name]
		if !ok {
			delta.DeletedFunctions = append(delta.DeletedFunctions, name)
			continue
		}
		if normalizeSig(before) != normalizeSig(after) {
			delta.ModifiedSignatures = append(delta.ModifiedSignatures, struct {
				Name   string `json:"name"`
				Before string `json:"before"`
				After  string `json:"after"`
			}{Name: name, Before: before, After: after})
		}
	}
	return delta
}

// ────────────────────────────────────────────────────────────────────────────
// Config-var rename detection (Pillar 24)
//
// Env-var names are extracted from added/removed lines of
// `git diff ref1 ref2 -U0 -- *.go` by parsing +lines/-lines for
// os.Getenv("X") / os.LookupEnv("X"). The removed-minus-added set and the
// added-minus-removed set are diffed: removed+added pairs with similarity
// (same prefix before the first '_' or levenshtein distance <= 3) are
// reported as renames; unpaired removed vars are pure deletions.
// ────────────────────────────────────────────────────────────────────────────

var getenvRe = regexp.MustCompile(`(?:Getenv|LookupEnv)\(\s*"([A-Z_][A-Z0-9_]*)"\s*[,)]`)

// diffConfigVarRenames returns (renamed pairs, pure removals) between two refs.
func diffConfigVarRenames(repoRoot, ref1, ref2 string) ([]struct {
	OldName string `json:"old_name"`
	NewName string `json:"new_name"`
}, []string) {
	cmd := exec.Command("git", "diff", ref1, ref2, "-U0", "--", "*.go")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return nil, nil
	}
	removedSet := make(map[string]bool)
	addedSet := make(map[string]bool)
	for _, line := range strings.Split(string(out), "\n") {
		if len(line) < 2 {
			continue
		}
		marker := line[0]
		if marker != '+' && marker != '-' {
			continue
		}
		if strings.HasPrefix(line, "+++") || strings.HasPrefix(line, "---") {
			continue
		}
		for _, m := range getenvRe.FindAllStringSubmatch(line[1:], -1) {
			if len(m) < 2 {
				continue
			}
			if marker == '-' {
				removedSet[m[1]] = true
			} else {
				addedSet[m[1]] = true
			}
		}
	}
	var removed, added []string
	for v := range removedSet {
		if !addedSet[v] {
			removed = append(removed, v)
		}
	}
	for v := range addedSet {
		if !removedSet[v] {
			added = append(added, v)
		}
	}
	sort.Strings(removed)
	sort.Strings(added)

	type rename struct {
		OldName string `json:"old_name"`
		NewName string `json:"new_name"`
	}
	var renamedPairs []rename
	used := make(map[string]bool)
	var pureRemoved []string
	for _, old := range removed {
		best := ""
		bestDist := -1
		for _, nw := range added {
			if used[nw] {
				continue
			}
			if !similarEnvName(old, nw) {
				continue
			}
			d := levenshtein(old, nw)
			if best == "" || d < bestDist {
				best = nw
				bestDist = d
			}
		}
		if best != "" {
			renamedPairs = append(renamedPairs, rename{OldName: old, NewName: best})
			used[best] = true
		} else {
			pureRemoved = append(pureRemoved, old)
		}
	}
	sort.Strings(pureRemoved)
	// Convert to the APIDelta anonymous struct type (identical fields+tags).
	renamed := make([]struct {
		OldName string `json:"old_name"`
		NewName string `json:"new_name"`
	}, 0, len(renamedPairs))
	for _, r := range renamedPairs {
		renamed = append(renamed, struct {
			OldName string `json:"old_name"`
			NewName string `json:"new_name"`
		}{OldName: r.OldName, NewName: r.NewName})
	}
	return renamed, pureRemoved
}

// similarEnvName reports whether two env-var names look like a rename:
// same prefix before the first '_' (e.g. OAUTH_* → OAUTH_*) or
// levenshtein distance <= 3 (e.g. PORT → PORTS, DB_HOST → DB_HOSTS).
func similarEnvName(a, b string) bool {
	if prefixBeforeUnderscore(a) == prefixBeforeUnderscore(b) && prefixBeforeUnderscore(a) != "" {
		return true
	}
	return levenshtein(a, b) <= 3
}

func prefixBeforeUnderscore(s string) string {
	if idx := strings.Index(s, "_"); idx > 0 {
		return s[:idx]
	}
	return s
}

// levenshtein returns the edit distance between two strings (small,
// allocation-light implementation for short env-var names).
func levenshtein(a, b string) int {
	ar, br := []rune(a), []rune(b)
	if len(ar) == 0 {
		return len(br)
	}
	if len(br) == 0 {
		return len(ar)
	}
	prev := make([]int, len(br)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(ar); i++ {
		cur := make([]int, len(br)+1)
		cur[0] = i
		for j := 1; j <= len(br); j++ {
			cost := 0
			if ar[i-1] != br[j-1] {
				cost = 1
			}
			cur[j] = min3(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev = cur
	}
	return prev[len(br)]
}

func min3(a, b, c int) int {
	if a > b {
		a = b
	}
	if a > c {
		a = c
	}
	return a
}

func exportedFuncName(sigLine string) string {
	// Forms: "func Name(...", "func (r Recv) Name(...".
	// Key includes the receiver so methods on different types never
	// collide (e.g. (*A).Render vs (*B).Render are distinct symbols).
	rest := strings.TrimPrefix(sigLine, "func ")
	rest = strings.TrimSpace(rest)
	receiver := ""
	if strings.HasPrefix(rest, "(") {
		if idx := strings.Index(rest, ")"); idx >= 0 {
			receiver = strings.TrimSpace(rest[:idx+1])
			rest = strings.TrimSpace(rest[idx+1:])
		}
	}
	fields := strings.Fields(rest)
	if len(fields) == 0 {
		return ""
	}
	name := strings.Split(fields[0], "(")[0]
	if !isExportedGoIdent(name) {
		return ""
	}
	if receiver != "" {
		recvType := receiver
		recvType = strings.TrimPrefix(recvType, "(")
		recvType = strings.TrimSuffix(recvType, ")")
		recvFields := strings.Fields(recvType)
		if len(recvFields) == 2 {
			recvType = recvFields[1]
		} else if len(recvFields) == 1 {
			recvType = recvFields[0]
		}
		recvType = strings.TrimPrefix(recvType, "*")
		return recvType + "." + name
	}
	return name
}

func parseTypeStructLine(line string) (string, bool) {
	// "type Name struct {" with optional spacing.
	if !strings.HasPrefix(line, "type ") || !strings.Contains(line, "struct") {
		return "", false
	}
	fields := strings.Fields(strings.TrimPrefix(line, "type "))
	if len(fields) == 0 {
		return "", false
	}
	return fields[0], true
}

func isExportedGoIdent(name string) bool {
	if name == "" {
		return false
	}
	c := name[0]
	return c >= 'A' && c <= 'Z'
}

func normalizeSig(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	replacer := strings.NewReplacer("( ", "(", " )", ")", " ,", ",")
	prev := ""
	for s != prev {
		prev = s
		s = replacer.Replace(s)
	}
	return s
}

// displayNameOf strips the file-qualification prefix (path::Name → Name)
// for human-readable rendering.
func displayNameOf(key string) string {
	if idx := strings.LastIndex(key, "::"); idx >= 0 {
		return key[idx+2:]
	}
	return key
}
